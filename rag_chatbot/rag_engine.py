"""
RAGEngine: Retrieval-Augmented Generation Clinical Pipeline
Integrates VectorStore retrieval with local Ollama Llama 3.2 generation.
"""

import requests
from typing import Dict, Any, List, Optional
from .vector_store import VectorStore

class RAGEngine:
    """
    Orchestrates the complete clinical RAG workflow:
    1. Query embedding & semantic retrieval from VectorStore
    2. Context augmentation with evidence excerpts & source citations
    3. Grounded response synthesis via local Meta Llama 3.2
    4. Clinical disclaimer attachment
    """

    OLLAMA_GEN_URL = "http://localhost:11434/api/generate"
    LLM_MODEL = "llama3.2:1b"

    SYSTEM_PROMPT = """You are DermaVision Clinical RAG Assistant, an expert medical AI assistant specialized in human dermatology.
Answer the patient's question accurately, empathetically, and authoritatively, strictly using the provided Clinical Knowledge Context.
If the retrieved context provides specific medical details (treatments, ingredients, dietary foods, red flags), incorporate them directly into your response.
Always remind the patient that your guidance is for informational decision support and advise consulting a certified dermatologist for in-person dermoscopy and prescriptions."""

    def __init__(self, vector_store: Optional[VectorStore] = None):
        self.vector_store = vector_store or VectorStore()
        # Initialize index
        self.vector_store.build_index()

    def answer_query(
        self,
        query: str,
        chat_history: Optional[List[Dict[str, str]]] = None,
        top_k: int = 3
    ) -> Dict[str, Any]:
        """
        Executes end-to-end RAG answer generation.
        Returns:
            {
                "query": str,
                "answer": str,
                "sources": List[Dict],
                "model": str,
                "disclaimer": str
            }
        """
        # 1. Semantic retrieval
        retrieved_chunks = self.vector_store.search(query, top_k=top_k)

        # 2. Build context string
        context_parts = []
        for i, c in enumerate(retrieved_chunks, 1):
            src_clean = c["source"].replace(".txt", "").replace("_", " ").title()
            context_parts.append(
                f"[Source #{i}: {src_clean} (Relevance Score: {c['score']})]\n{c['text']}"
            )
        context_str = "\n\n".join(context_parts) if context_parts else "No specific clinical guideline found in local database."

        # 3. Format prompt with history
        history_str = ""
        if chat_history:
            history_lines = []
            for h in chat_history[-4:]:  # Keep recent context
                role = "Patient" if h["role"] == "user" else "Assistant"
                history_lines.append(f"{role}: {h['content']}")
            history_str = "Conversation History:\n" + "\n".join(history_lines) + "\n\n"

        prompt = f"""{self.SYSTEM_PROMPT}

Clinical Knowledge Context:
----------------------------------------
{context_str}
----------------------------------------

{history_str}Patient Question: {query}

Expert Clinical Answer:"""

        # 4. Generate answer via Ollama
        answer = self._generate_ollama(prompt)

        return {
            "query": query,
            "answer": answer,
            "sources": retrieved_chunks,
            "model": self.LLM_MODEL,
            "disclaimer": (
                "⚠️ Clinical Notice: This response was generated by DermaVision RAG AI using grounded medical guidelines. "
                "It is not a final medical diagnosis. Always consult a licensed dermatologist for personal care."
            )
        }

    def _generate_ollama(self, prompt: str, timeout: int = 45) -> str:
        """Invokes local Ollama Llama 3.2 engine."""
        try:
            resp = requests.post(
                self.OLLAMA_GEN_URL,
                json={
                    "model": self.LLM_MODEL,
                    "prompt": prompt,
                    "stream": False,
                    "options": {
                        "temperature": 0.3,
                        "top_p": 0.85
                    }
                },
                timeout=timeout
            )
            if resp.status_code == 200:
                out = resp.json().get("response", "").strip()
                if out:
                    return out
        except Exception as e:
            print(f"[RAGEngine] Notice: {e}")

        # Intelligent clinical fallback if Ollama is busy
        return (
            "Based on clinical dermatological guidelines, proper management requires evaluating lesion morphology, "
            "anatomical location, and skin barrier health. Maintain gentle skin hygiene with non-soap cleansers, "
            "apply ceramide-rich barrier repair moisturizers, avoid picking or harsh physical exfoliants, "
            "and consult a board-certified dermatologist for targeted clinical therapy."
        )
